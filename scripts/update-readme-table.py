#!/usr/bin/env python3
"""update-readme-table.py — regenerate the Compatibility table in README.md
by walking `git tag -l 'v*'` and reading each tag's compatibility.yaml.

The output is written between `<!-- COMPAT:BEGIN -->` and
`<!-- COMPAT:END -->` markers in README.md. Tags that don't carry a
compatibility.yaml (pre-v1.1.4) are listed with `(no manifest)` so
users can see the full history.

Modes:
    (default)  —  overwrite README.md in place
    --check    —  render to memory, byte-diff with on-disk file;
                  exit 1 on drift (for pre-commit / CI)
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError as e:  # pragma: no cover
    print(f"error: pyyaml not available ({e})", file=sys.stderr)
    sys.exit(2)


BEGIN = "<!-- COMPAT:BEGIN -->"
END = "<!-- COMPAT:END -->"


def list_tags(repo_root: Path) -> list[str]:
    """Return v* tags sorted by creator date (oldest first)."""
    out = subprocess.check_output(
        [
            "git", "-C", str(repo_root),
            "for-each-ref",
            "--sort=creatordate",
            "--format=%(refname:short)",
            "refs/tags/v*",
        ],
        text=True,
    )
    return [t.strip() for t in out.splitlines() if t.strip()]


def read_compat_at_tag(repo_root: Path, tag: str) -> dict | None:
    """Return the parsed compatibility.yaml at the given tag, or None."""
    try:
        raw = subprocess.check_output(
            ["git", "-C", str(repo_root), "show", f"{tag}:compatibility.yaml"],
            stderr=subprocess.DEVNULL,
            text=True,
        )
    except subprocess.CalledProcessError:
        return None
    try:
        return yaml.safe_load(raw)
    except yaml.YAMLError:
        return None


def render_table(repo_root: Path, pending_tag: str | None = None,
                 pending_compat: dict | None = None) -> str:
    """Render the markdown table body (no markers).

    pending_tag/pending_compat allow previewing an unreleased tag + its
    staged compat yaml — useful when running this script right before
    `git tag` lands.
    """
    tags = list_tags(repo_root)
    if pending_tag and pending_tag not in tags:
        tags.append(pending_tag)

    rows: list[str] = []
    for tag in tags:
        if tag == pending_tag and pending_compat is not None:
            compat = pending_compat
        else:
            compat = read_compat_at_tag(repo_root, tag)

        if compat is None:
            rows.append(f"| `{tag}` | _(no manifest; pre-v1.1.4)_ |")
            continue

        kg = compat.get("zmk_known_good", {})
        lower = kg.get("lower", "?")
        upper = kg.get("upper") or "HEAD-at-release"
        branch = kg.get("branch_hint", "main")
        rows.append(f"| `{tag}` | ZMK `{lower}` .. `{upper}` (branch `{branch}`) |")

    body = [
        "",
        "| zmk-keybeacon tag | Known-good ZMK revision range |",
        "|---|---|",
        *rows,
        "",
        "_This table is generated by `scripts/update-readme-table.py` from each "
        "tag's `compatibility.yaml`. Do not hand-edit between the markers._",
        "",
    ]
    return "\n".join(body)


def apply_to_readme(readme_text: str, table_body: str) -> str:
    """Replace the content between BEGIN..END markers with table_body."""
    pattern = re.compile(
        rf"({re.escape(BEGIN)})(.*?)({re.escape(END)})",
        re.DOTALL,
    )
    if not pattern.search(readme_text):
        raise RuntimeError(f"README missing {BEGIN} / {END} markers")
    return pattern.sub(rf"\1\n{table_body}\n\3", readme_text, count=1)


def main() -> int:
    here = Path(__file__).resolve().parent
    module_root = here.parent

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--readme", type=Path, default=module_root / "README.md")
    parser.add_argument("--repo-root", type=Path, default=module_root)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit 1 if README would change.",
    )
    parser.add_argument(
        "--pending-tag",
        default=None,
        help="Treat this (unreleased) tag as if it were present, using the "
             "working-tree compatibility.yaml as its manifest.",
    )
    args = parser.parse_args()

    pending_compat = None
    if args.pending_tag:
        pending_yaml = args.repo_root / "compatibility.yaml"
        pending_compat = yaml.safe_load(pending_yaml.read_text(encoding="utf-8"))

    table = render_table(args.repo_root, args.pending_tag, pending_compat)
    readme_text = args.readme.read_text(encoding="utf-8")
    new_text = apply_to_readme(readme_text, table)

    if args.check:
        if readme_text == new_text:
            print("update-readme-table --check: README is in sync")
            return 0
        diff = "\n".join(
            difflib.unified_diff(
                readme_text.splitlines(),
                new_text.splitlines(),
                fromfile="README.md (on disk)",
                tofile="README.md (regenerated)",
                lineterm="",
            )
        )
        print(diff, file=sys.stderr)
        print(
            "error: README Compatibility table drifted. "
            "Run `python3 scripts/update-readme-table.py` and commit.",
            file=sys.stderr,
        )
        return 1

    args.readme.write_text(new_text, encoding="utf-8")
    print(f"update-readme-table: wrote {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
